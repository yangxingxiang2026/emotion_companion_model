/** 随机取一条 */
function pick(list) {
  return list[Math.floor(Math.random() * list.length)];
}

/**
 * 关键词匹配（危机优先，避免被其他规则抢占）
 * @param {string} text 用户输入
 * @returns {object|null} 命中的规则
 */
function matchRule(text) {
  // 去空白并转小写，提升口语化/带空格输入的命中率
  var normalized = String(text || '').replace(/\s+/g, '').toLowerCase();
  if (!normalized) return null;

  for (var i = 0; i < RULES.length; i++) {
    var rule = RULES[i];
    for (var j = 0; j < rule.keywords.length; j++) {
      if (normalized.indexOf(rule.keywords[j].toLowerCase()) !== -1) {
        return rule;
      }
    }
  }
  return null;
}

/**
 * 对外主入口：根据用户输入返回模拟回复
 * @param {string} text 用户输入
 * @returns {{content: string, crisis: boolean, scene: string}}
 */
function getReply(text) {
  var rule = matchRule(text);
  return {
    content: pick(rule ? rule.replies : DEFAULT_REPLIES),
    crisis: !!(rule && rule.crisis),
    scene: rule ? rule.name : 'default'
  };
}

